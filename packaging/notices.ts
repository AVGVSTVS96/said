import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { basename, dirname, join, resolve } from "node:path";

interface Package {
  id: string;
  name: string;
  version: string;
  source: string | null;
  manifest_path: string;
  license: string | null;
  license_file: string | null;
}
interface Metadata {
  packages: Package[];
  resolve: { nodes: { id: string; dependencies: string[] }[] };
}
interface LicenseSource { file: string; url: string; sha256: string }

const root = resolve(import.meta.dir, "..");
const output = process.argv[2];
if (!output) throw new Error("Supply a dependency notice output file");
const hash = (bytes: string | Uint8Array) => createHash("sha256").update(bytes).digest("hex");
const upstream: Record<string, LicenseSource[]> = JSON.parse(readFileSync(join(root, "licenses/upstream.json"), "utf8"));
const packages = new Map<string, Package>();
for (const platform of ["x86_64-unknown-linux-gnu", "aarch64-apple-darwin"]) {
  const result = Bun.spawnSync(["cargo", "metadata", "--locked", "--format-version", "1",
    "--features", "said-app/custom-protocol", "--filter-platform", platform], { cwd: root });
  if (result.exitCode !== 0) throw new Error(result.stderr.toString());
  const metadata: Metadata = JSON.parse(result.stdout.toString());
  const nodes = new Map(metadata.resolve.nodes.map(node => [node.id, node]));
  const pending = metadata.packages.filter(pkg => pkg.name === "said-app").map(pkg => pkg.id);
  const reached = new Set<string>();
  while (pending.length) {
    const id = pending.pop()!;
    if (reached.has(id)) continue;
    reached.add(id);
    pending.push(...nodes.get(id)!.dependencies);
  }
  for (const pkg of metadata.packages) {
    if (pkg.source && reached.has(pkg.id)) packages.set(pkg.id, pkg);
  }
}

const texts = new Map<string, { text: string; components: Set<string> }>();
const inventory: string[] = [];
function retain(component: string, file: string, expected?: string) {
  const bytes = readFileSync(file);
  const digest = hash(bytes);
  if (expected && expected !== digest) throw new Error(`License hash mismatch: ${component}`);
  const entry = texts.get(digest) ?? { text: bytes.toString("utf8"), components: new Set<string>() };
  entry.components.add(component);
  texts.set(digest, entry);
}
function licenseFiles(directory: string) {
  return [...new Bun.Glob("**/*").scanSync({ cwd: directory, onlyFiles: true, followSymlinks: true })]
    .filter(file => /^(licen[cs]e|copying|copyright|notice|ofl)([._-]|$)/i.test(basename(file)))
    .filter(file => !file.endsWith(".spdx"))
    .sort();
}
for (const pkg of [...packages.values()].sort((a, b) => `${a.name}@${a.version}`.localeCompare(`${b.name}@${b.version}`, "en"))) {
  const component = `${pkg.name}@${pkg.version}`;
  const directory = dirname(pkg.manifest_path);
  const files = licenseFiles(directory);
  inventory.push(`${component} | ${pkg.license ?? "see supplied terms"} | https://crates.io/crates/${pkg.name}/${pkg.version}`);
  for (const file of files) retain(`${component}: ${file}`, join(directory, file));
  if (pkg.license_file && !files.includes(pkg.license_file)) {
    retain(`${component}: ${pkg.license_file}`, join(directory, pkg.license_file));
    files.push(pkg.license_file);
  }
  if (!files.length) {
    const sources = upstream[component];
    if (!sources?.length) throw new Error(`Missing license texts: ${component}`);
    for (const source of sources) retain(`${component}: ${source.url}`, join(root, source.file), source.sha256);
  }
}

const frontend = JSON.parse(readFileSync(join(root, "app/package.json"), "utf8"));
const pending = Object.keys(frontend.dependencies);
const reached = new Set<string>();
while (pending.length) {
  const name = pending.pop()!;
  if (reached.has(name)) continue;
  reached.add(name);
  const directory = join(root, "app/node_modules", name);
  const pkg = JSON.parse(readFileSync(join(directory, "package.json"), "utf8"));
  const component = `${pkg.name}@${pkg.version}`;
  inventory.push(`${component} | ${pkg.license ?? "see supplied terms"} | https://www.npmjs.com/package/${pkg.name}/v/${pkg.version}`);
  const files = licenseFiles(directory).filter(file => !file.startsWith("node_modules/"));
  if (!files.length) throw new Error(`Missing license texts: ${component}`);
  for (const file of files) retain(`${component}: ${file}`, join(directory, file));
  pending.push(...Object.keys(pkg.dependencies ?? {}));
}

const header = `Third-party Rust and JavaScript dependency notices\n\nGenerated by packaging/notices.ts.\nCargo.lock SHA-256: ${hash(readFileSync(join(root, "Cargo.lock")))}\napp/bun.lock SHA-256: ${hash(readFileSync(join(root, "app/bun.lock")))}\n\nThis is the union of the said-app dependency graphs on Linux x86_64 and Apple Silicon,\nincluding build/test dependencies, plus production frontend dependencies. It can\ninclude components absent from an individual binary. Upstream license expressions\nand texts are retained; this inventory does not change their licensing.\nMPL-covered source is available from the versioned crate source links below.\nSource archives can be obtained at https://crates.io/api/v1/crates/NAME/VERSION/download.\n\n${inventory.sort().join("\n")}\n\n`;
writeFileSync(output, header + [...texts.values()].map(entry =>
  `${"=".repeat(72)}\n${[...entry.components].sort().join("\n")}\n\n${entry.text}\n`).join("\n"));
console.log(`Retained ${inventory.length} dependencies and ${texts.size} distinct license/notice texts`);
